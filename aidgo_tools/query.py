"""Run the competency-question queries in queries/*.rq against the built KG.

    python -m aidgo_tools query              # run all, write output/cq_results/*.csv + summary
    python -m aidgo_tools query CQ-M1        # run one and print it
    python -m aidgo_tools query path/to.rq   # run an arbitrary query file
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import pyoxigraph as ox

from . import paths
from .build import load_store

_SHORT = sorted(paths.PREFIXES.items(), key=lambda kv: -len(kv[1]))


def term_str(t) -> str:
    if t is None:
        return ""
    if isinstance(t, ox.NamedNode):
        for p, ns in _SHORT:
            if t.value.startswith(ns):
                return f"{p}:{t.value[len(ns):]}"
        return t.value
    if isinstance(t, ox.Literal):
        return t.value
    return str(t)


def run(query_text: str, store: ox.Store | None = None) -> tuple[list[str], list[list[str]]]:
    store = store or load_store(star=True)
    res = store.query(query_text)
    cols = [v.value for v in res.variables]
    rows = [[term_str(sol[c]) for c in cols] for sol in res]
    return cols, rows


def query_files() -> list[Path]:
    return sorted(paths.QUERIES.glob("*.rq"))


def resolve(name: str) -> Path:
    p = Path(name)
    if p.exists():
        return p
    p = paths.QUERIES / (name if name.endswith(".rq") else name + ".rq")
    if not p.exists():
        raise SystemExit(f"no such query: {name}")
    return p


def title(p: Path) -> str:
    first = p.read_text(encoding="utf-8").splitlines()[0]
    return first.lstrip("# ").strip()


def print_table(cols: list[str], rows: list[list[str]], width: int = 60) -> None:
    clip = lambda s: s if len(s) <= width else s[: width - 1] + "…"  # noqa: E731
    w = [max([len(c)] + [len(clip(r[i])) for r in rows]) for i, c in enumerate(cols)]
    print("  " + " | ".join(c.ljust(w[i]) for i, c in enumerate(cols)))
    print("  " + "-+-".join("-" * x for x in w))
    for r in rows:
        print("  " + " | ".join(clip(v).ljust(w[i]) for i, v in enumerate(r)))


def main(argv: list[str]) -> int:
    store = load_store(star=True)
    if argv:
        for name in argv:
            p = resolve(name)
            cols, rows = run(p.read_text(encoding="utf-8"), store)
            print(f"\n{title(p)}  ({len(rows)} rows)")
            print_table(cols, rows)
        return 0
    out = paths.OUTPUT / "cq_results"
    out.mkdir(parents=True, exist_ok=True)
    summary = ["# Competency question results", "",
               "Generated by `python -m aidgo_tools query` against `output/aidgo_kg_star.ttl`.", "",
               "| Query | Question | Rows |", "|---|---|---|"]
    for p in query_files():
        cols, rows = run(p.read_text(encoding="utf-8"), store)
        with (out / f"{p.stem}.csv").open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh, lineterminator="\n")
            w.writerow(cols)
            w.writerows(rows)
        q = title(p).split(":", 1)
        summary.append(f"| [{p.stem}](../../queries/{p.name}) | {q[-1].strip()} | {len(rows)} |")
        print(f"  {p.stem:16} {len(rows):4} rows")
    (out / "README.md").write_text("\n".join(summary) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
